"""Strict structured protocol over EMF's existing console bridge."""
import json
import re
import time
from uuid import uuid4

PREFIX = "AIC_BODY "
ACTIONS = frozenset({"spawn", "follow", "stay", "dismiss"})
TOKEN = re.compile(r"[A-Za-z0-9_-]{1,96}\Z")


class ClientError(RuntimeError):
    def __init__(self, code, detail=None):
        self.code, self.detail = code, detail
        super().__init__(code)


def token(value):
    if not isinstance(value, str) or not TOKEN.fullmatch(value):
        raise ClientError("invalid_token")
    return value


class BodyClient:
    def __init__(self, bridge, *, clock=time.monotonic, sleep=time.sleep, trace=None):
        self.bridge, self.clock, self.sleep = bridge, clock, sleep
        self.trace = trace or (lambda event, data: None)

    def observe(self, method):
        self.trace('observation_sent', {'method': method})
        try:
            result = getattr(self.bridge, method)()
        except Exception as exc:
            self.trace('observation_error', {'method': method, 'error': str(exc)})
            raise ClientError('bridge_connection_error', str(exc)) from exc
        self.trace('observation_received', {'method': method, 'result': result})
        if not isinstance(result, dict) or result.get('ok') is not True:
            raise ClientError('malformed_bridge_observation', result)
        return result

    def console(self, line):
        # Only our two command names are ever generated by this client.
        self.trace('console_sent', {'command': line})
        try:
            response = self.bridge.console(line, timeout_ms=3000, settle_ms=0)
        except Exception as exc:
            self.trace('console_error', {'command': line, 'error': str(exc), 'outcome': 'unknown'})
            raise ClientError("bridge_error_outcome_unknown", str(exc)) from exc
        self.trace('console_received', {'command': line, 'result': response})
        if not isinstance(response, dict) or response.get("ok") is not True or response.get("status") != "ran":
            raise ClientError("console_refused", response)
        output = response.get("output")
        if not isinstance(output, list):
            raise ClientError("malformed_console_reply")
        payloads = [x[len(PREFIX):] for x in output if isinstance(x, str) and x.startswith(PREFIX)]
        if len(payloads) != 1:
            raise ClientError("adapter_reply_missing_or_ambiguous", response)
        try:
            payload = json.loads(payloads[0])
        except ValueError as exc:
            raise ClientError("malformed_adapter_json") from exc
        if not isinstance(payload, dict) or payload.get("protocol") != 1:
            raise ClientError("unsupported_adapter_protocol")
        if payload.get("error"):
            raise ClientError(str(payload["error"]), payload)
        state = payload.get("state")
        if not isinstance(state, dict) or state.get("protocol") != 1:
            raise ClientError("malformed_body_state")
        token(state.get("epoch"))
        token(state.get("session"))
        return payload

    def status(self, request_id=None):
        suffix = " " + token(request_id) if request_id is not None else ""
        return self.console("aic_body.status" + suffix)

    def preflight(self, *, world_slot, character_slot, character_name):
        """Fail closed: a pinned build, local host world and explicitly selected test character."""
        hello, state = self.observe('hello'), self.observe('state')
        if hello.get("protocol") != 1 or hello.get("api") != 20 or hello.get("emf") != "0.3.2":
            raise ClientError("unsupported_emf", hello)
        if hello.get("game_build") != 1273043 or hello.get("process") != "client":
            raise ClientError("unsupported_game_build_or_process", hello)
        world, character = state.get("world") or {}, state.get("character") or {}
        if (world.get("status") != "running" or world.get("kind") != "server"
                or type(world_slot) is not int or not 1 <= world_slot <= 10 or world.get("slot") != world_slot):
            raise ClientError("wrong_test_world", state)
        if (character.get("storage") != "local" or type(character_slot) is not int
                or not 1 <= character_slot <= 16 or character.get("slot") != character_slot
                or not character_name or character.get("name") != character_name):
            raise ClientError("wrong_test_character", state)
        if not (state.get("player") or {}).get("id"):
            raise ClientError("host_player_missing", state)
        return hello, state

    def execute(self, action, companion_id, *, allow_mutations=False, request_id=None,
                world_slot=None, character_slot=None, character_name=None, timeout=40):
        if not allow_mutations:
            raise ClientError("game_mutations_not_authorized")
        if action not in ACTIONS:
            raise ClientError("unsupported_action")
        if not isinstance(timeout, (int, float)) or not 0 < timeout <= 120:
            raise ClientError("invalid_timeout")
        identity = token(companion_id)
        rid = token(request_id if request_id is not None else uuid4().hex)
        before = self.status()["state"]
        epoch = before["epoch"]
        # Capture epoch BEFORE the world check. Any later world transition must
        # make the adapter reject this epoch, not silently select the new world.
        self.preflight(world_slot=world_slot, character_slot=character_slot, character_name=character_name)
        if before.get("recovery_required"):
            raise ClientError("recovery_required", before)
        def request_console(line):
            try:
                return self.console(line)
            except ClientError as exc:
                raise ClientError(exc.code, {"request_id": rid, "epoch": epoch,
                                             "action": action, "cause": exc.detail}) from exc
        started = self.clock()
        result = request_console(f"aic_body.request {rid} {epoch} {identity} {action}")
        while True:
            if result["state"]["epoch"] != epoch:
                raise ClientError("session_or_adapter_changed", {"request_id": rid, "result": result})
            request = result.get("request")
            if (not isinstance(request, dict) or request.get("id") != rid
                    or request.get("action") != action or request.get("companion_id") != identity):
                raise ClientError("request_correlation_failed", result)
            status = request.get("status")
            if status == "succeeded":
                return result
            if status in {"failed", "cancelled"}:
                raise ClientError("body_command_" + status, result)
            if status != "accepted":
                raise ClientError("invalid_request_status", result)
            if self.clock()-started >= timeout:
                raise ClientError("verification_timeout_outcome_unknown", {"request_id": rid, "epoch": epoch,
                                                                          "last_result": result})
            self.sleep(0.2)
            result = request_console("aic_body.status " + rid)

    def diagnose(self):
        result = {"hello": self.observe('hello'), "game": self.observe('state')}
        try:
            result["body"] = self.status()
        except ClientError as exc:
            result["body_error"] = {"code": exc.code, "detail": exc.detail}
        return result
